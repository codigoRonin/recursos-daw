CREATE DATABASE IF NOT EXISTS transporte;
USE transporte;

DROP TABLE IF EXISTS solicitudes, viajes, ruta_parada, viajeros, conductores, vehiculos, paradas, rutas;

CREATE TABLE rutas (
    cod_ruta    CHAR(2)      PRIMARY KEY,
    nombre_ruta VARCHAR(60)  NOT NULL,
    km_ruta     DECIMAL(4,1) NOT NULL,
    tarifa      DECIMAL(4,2) NOT NULL
);

CREATE TABLE paradas (
    cod_parada    INT         PRIMARY KEY,
    nombre_parada VARCHAR(60) NOT NULL,
    municipio     VARCHAR(40) NOT NULL,
    marquesina    TINYINT     NOT NULL
);

CREATE TABLE ruta_parada (
    cod_ruta   CHAR(2) NOT NULL,
    cod_parada INT     NOT NULL,
    orden      INT     NOT NULL,
    minuto     INT     NOT NULL,
    PRIMARY KEY (cod_ruta, cod_parada),
    FOREIGN KEY (cod_ruta)   REFERENCES rutas(cod_ruta),
    FOREIGN KEY (cod_parada) REFERENCES paradas(cod_parada)
);

CREATE TABLE vehiculos (
    matricula          CHAR(8) PRIMARY KEY,
    plazas             INT     NOT NULL,
    anio_matriculacion INT     NOT NULL,
    adaptado           TINYINT NOT NULL,
    itv_hasta          DATE
);

CREATE TABLE conductores (
    cod_conductor    INT         PRIMARY KEY,
    nombre_conductor VARCHAR(60) NOT NULL,
    alta_conductor   DATE        NOT NULL,
    movil            VARCHAR(15)
);

CREATE TABLE viajeros (
    cod_viajero     INT         PRIMARY KEY,
    nombre_viajero  VARCHAR(60) NOT NULL,
    municipio       VARCHAR(40),
    anio_nacimiento INT,
    tarjeta         VARCHAR(10),
    alta_viajero    DATE        NOT NULL
);

CREATE TABLE viajes (
    cod_viaje     INT     PRIMARY KEY,
    cod_ruta      CHAR(2) NOT NULL,
    dia           DATE    NOT NULL,
    hora_salida   TIME    NOT NULL,
    matricula     CHAR(8),
    cod_conductor INT,
    FOREIGN KEY (cod_ruta)      REFERENCES rutas(cod_ruta),
    FOREIGN KEY (matricula)     REFERENCES vehiculos(matricula),
    FOREIGN KEY (cod_conductor) REFERENCES conductores(cod_conductor)
);

CREATE TABLE solicitudes (
    cod_solicitud  INT         PRIMARY KEY,
    cod_viaje      INT         NOT NULL,
    cod_viajero    INT         NOT NULL,
    sube_en        INT         NOT NULL,
    baja_en        INT         NOT NULL,
    plazas_pedidas INT         NOT NULL,
    estado         VARCHAR(15) NOT NULL,
    valoracion     INT,
    FOREIGN KEY (cod_viaje)   REFERENCES viajes(cod_viaje),
    FOREIGN KEY (cod_viajero) REFERENCES viajeros(cod_viajero),
    FOREIGN KEY (sube_en)     REFERENCES paradas(cod_parada),
    FOREIGN KEY (baja_en)     REFERENCES paradas(cod_parada)
);

